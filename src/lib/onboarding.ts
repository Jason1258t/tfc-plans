/**
 * Подсказки знакомства: при первом входе в раздел — несколько шагов с подсветкой элементов страницы.
 * Цель шага — CSS-селектор (и, если нужно, текст внутри элемента); не нашлась — шаг показывается посередине экрана.
 * Подробности — в гайдах «О сайте» (ссылка guide).
 */

export interface TourStep {
  /** Что подсветить: селектор, через запятую — запасные; без цели — посередине */
  target?: string;
  /** Среди найденных по селектору — элемент с этим текстом */
  text?: string;
  title: string;
  body: string;
}

export interface Tour {
  key: string;
  /** Как раздел называется в меню «?» */
  label: string;
  steps: TourStep[];
  /** id гайда раздела «О сайте» — ссылка «Подробнее» */
  guide?: string;
}

const T = (key: string, label: string, guide: string | undefined, steps: TourStep[]): Tour => ({
  key,
  label,
  guide,
  steps,
});

