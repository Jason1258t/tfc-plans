/** Подсказки для открытой страницы; null — у страницы их нет */
export function tourFor(pathname: string, search: string): Tour | null {
  const q = new URLSearchParams(search);
  let key: string | null = null;
  if (pathname === '/') key = q.get('view') === 'docs' ? 'plans' : 'tasks';
  else if (pathname === '/docs') key = 'docs';
  else if (pathname === '/schematics') key = 'schematics';
  else if (pathname === '/datapacks') key = 'datapacks';
  else if (pathname === '/recipes') key = 'recipes';
  else if (pathname === '/tags') key = 'tags';
  else if (pathname === '/addons') key = 'addons';
  else if (pathname === '/updates') key = 'updates';
  else if (pathname === '/reference') {
    const tab = q.get('tab');
    key = tab === null || tab === 'ores' ? 'ref-ores' : (REF_TABS[tab] ?? null);
  }
  return TOURS.find((t) => t.key === key) ?? null;
}

/** Запрос «показать подсказки» из меню «?» — их ловит Onboarding */
export const tourRequests = new EventTarget();

export const requestTour = (tour: Tour) => tourRequests.dispatchEvent(new CustomEvent('tour', { detail: tour }));
